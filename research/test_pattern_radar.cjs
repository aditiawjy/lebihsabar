source=source.slice(0,source.indexOf('  function renderPatternTable(lines)'))+'globalThis.radar=l16NextSlotRadar;})();';
const c={document:{createElement:()=>({}),getElementById:()=>null,head:{append(){}},body:{append(){}}},setTimeout:()=>0,clearTimeout(){}};
